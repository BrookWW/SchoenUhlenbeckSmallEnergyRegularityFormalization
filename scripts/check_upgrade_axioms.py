def main():
    modules = ["HolderToCK", "HolderToCK.Regularity"] + CHECKED_MODULES + [a["path"].removesuffix(".lean").replace("/", ".")
                              for a in SEALED_TARGETS]
    code = "module\n" + "\n".join("public import " + m for m in modules)
    code += "\nmeta import Lean\nopen Lean\n"
    code += "run_cmd do\n  let env ← getEnv\n  for n in ["
    code += ", ".join(chr(96) * 2 + name for name in EXPORTS)
    code += """] do
    let some _ := env.find? n | throwError "missing export: {n}"
    let axioms ← Lean.collectAxioms n
    logInfo ("AXIOMJSON " ++ n.toString ++ " " ++ (toJson (axioms.toList.map Name.toString)).compress)
"""
    result = subprocess.run(["lake", "--no-build", "env", "lean", "--stdin"],
                            input=code, capture_output=True, text=True, cwd=ROOT)
    if result.returncode:
        raise SystemExit(result.stdout + result.stderr)
    records = {}
    for line in result.stdout.splitlines():
        if line.startswith("AXIOMJSON "):
            _, name, payload = line.split(" ", 2)
            if name not in EXPORTS or name in records:
                raise SystemExit("Unexpected or duplicate axiom record")
            axioms = json.loads(payload)
            if not isinstance(axioms, list) or not all(isinstance(x, str) for x in axioms):
                raise SystemExit("Malformed axiom record")
            if set(axioms) - ALLOWED:
                raise SystemExit("Disallowed axioms: " + name)
            records[name] = axioms
    if set(records) != set(EXPORTS):
        raise SystemExit("Missing axiom records")
    for name in EXPORTS:
        print("AXIOMS OK", name, ", ".join(sorted(records[name])) or "none")
    print("CURRENT INTERFACE/INPUT AXIOM CHECK PASS:", len(EXPORTS), "exports")
    print("SEALED TARGET AXIOMS CHECKED:", len(SEALED_TARGETS),
          "; source certification is recorded separately")


if __name__ == "__main__":
    main()
